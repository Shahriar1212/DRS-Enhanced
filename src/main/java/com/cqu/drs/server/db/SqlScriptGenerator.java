/**
 * Writes {@code database/drs_enhanced.sql}: a stand-alone MySQL script that creates
 * the database, every table (same DDL as {@link Schema}) and populates it with the
 * default accounts, shelters and the DRS-Initial (Assessment 2) data. Encrypted
 * columns use the project's master key so the server can read them.
 * <p>Run: right-click this file in NetBeans &gt; Run File.</p>
 */
public final class SqlScriptGenerator {

    private static final DateTimeFormatter TS = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm:ss.SSS");

    private SqlScriptGenerator() {
    }

    public static void main(String[] args) throws IOException {
        Path out = Paths.get(args.length > 0 ? args[0] : "database/drs_enhanced.sql");
        CryptoService crypto = CryptoService.loadOrCreate(Paths.get("security/drs-master.key"));
        Files.createDirectories(out.getParent());
        Files.writeString(out, generate(crypto), StandardCharsets.UTF_8);
        System.out.println("Wrote " + out.toAbsolutePath());
    }

    static String q(String s) {
        return s == null ? "NULL" : "'" + s.replace("\\", "\\\\").replace("'", "''") + "'";
    }

    static String generate(CryptoService crypto) throws IOException {
        String now = "'" + LocalDateTime.now().format(TS) + "'";
        StringBuilder sb = new StringBuilder();
        sb.append("-- =====================================================================\n")
          .append("-- DRS-Enhanced (COIT20258 Assessment 3) - MySQL 8 database script\n")
          .append("-- Creates database drs_enhanced, all 12 tables and the initial data:\n")
          .append("--   * default accounts (admin/Admin@123, coord/Coord@123, officer/Officer@123, public/Public@123)\n")
          .append("--   * departments, resources, volunteers and disaster reports collected with DRS-Initial (A2)\n")
          .append("--   * evacuation shelters\n")
          .append("-- NOTE: the server also creates the database/tables automatically on start-up,\n")
          .append("--       so running this script is optional. Phone numbers and private keys are\n")
          .append("--       AES-GCM encrypted with security/drs-master.key (keep that file with the project).\n")
          .append("-- Generated by com.cqu.drs.server.db.SqlScriptGenerator\n")
          .append("-- =====================================================================\n\n")
          .append("DROP DATABASE IF EXISTS drs_enhanced;\n")
          .append("CREATE DATABASE drs_enhanced CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;\n")
          .append("USE drs_enhanced;\n\n");
        for (String ddl : Schema.ALL_TABLES) {
            sb.append(pretty(ddl.replaceFirst("CREATE TABLE IF NOT EXISTS", "CREATE TABLE"))).append(";\n\n");
        }

        // ---- users ----
        sb.append("-- Users (PBKDF2 password hashes, RSA-2048 key pairs; private keys AES-encrypted)\n");
        Map<String, PrivateKey> keys = new LinkedHashMap<>();
        int uid = 1;
        for (String[] u : DataSeeder.DEFAULT_USERS) {
            KeyPair kp = SignatureService.generateKeyPair();
            keys.put(u[0], kp.getPrivate());
            sb.append("INSERT INTO users (user_id, username, full_name, password_hash, role, public_key, private_key_enc, active, failed_attempts, created_at) VALUES (")
              .append(uid++).append(", ").append(q(u[0])).append(", ").append(q(u[1])).append(", ")
              .append(q(PasswordHasher.hash(u[2]))).append(", ").append(q(u[3])).append(", ")
              .append(q(SignatureService.encodePublicKey(kp.getPublic()))).append(", ")
              .append(q(crypto.encrypt(SignatureService.encodePrivateKey(kp.getPrivate())))).append(", TRUE, 0, ")
              .append(now).append(");\n");
        }

        // ---- departments + resources ----
        sb.append("\n-- Departments (DRS-Initial + Waste Management and Schools added in DRS-Enhanced)\n");
        List<Department> departments = new ArrayList<>();
        List<String[]> deptRows = new ArrayList<>(read("departments.csv"));
        deptRows.add(new String[]{"Waste Management Services", "WASTE_MANAGEMENT", "07 4000 7777"});
        deptRows.add(new String[]{"Regional Schools Office", "SCHOOLS", "07 4000 8888"});
        int did = 1;
        for (String[] f : deptRows) {
            Department d = new Department(f[0], DepartmentType.valueOf(f[1]), f[2]);
            d.setDepartmentId(did++);
            departments.add(d);
            sb.append("INSERT INTO departments (department_id, name, type, contact_info, created_at) VALUES (")
              .append(d.getDepartmentId()).append(", ").append(q(d.getName())).append(", ").append(q(f[1]))
              .append(", ").append(q(f[2])).append(", ").append(now).append(");\n");
        }
        sb.append("\n-- Resources\n");
        List<String[]> resRows = new ArrayList<>(read("resources.csv"));
        resRows.add(new String[]{"Waste Management Services", "Skip bins", "60", "10"});
        resRows.add(new String[]{"Waste Management Services", "Debris trucks", "12", "3"});
        resRows.add(new String[]{"Regional Schools Office", "Classroom kits", "80", "15"});
        int rid = 1;
        for (String[] f : resRows) {
            int deptId = departments.stream().filter(d -> d.getName().equals(f[0])).findFirst()
                    .orElseThrow().getDepartmentId();
            sb.append("INSERT INTO resources (resource_id, department_id, name, quantity_available, reorder_level, updated_at) VALUES (")
              .append(rid++).append(", ").append(deptId).append(", ").append(q(f[1])).append(", ").append(f[2])
              .append(", ").append(f[3]).append(", ").append(now).append(");\n");
        }

        // ---- shelters ----
        sb.append("\n-- Evacuation shelters (new feature 1)\n");
        String[][] shelters = {
                {"Rockhampton Showgrounds", "Rockhampton", "500", "07 4900 1000"},
                {"Yeppoon Community Hall", "Yeppoon", "150", "07 4900 2000"},
                {"Gladstone Entertainment Centre", "Gladstone", "300", "07 4900 3000"},
                {"CQUniversity Gym", "Rockhampton North", "200", "07 4900 4000"}};
        int sid = 1;
        for (String[] s : shelters) {
            sb.append("INSERT INTO shelters (shelter_id, name, location, capacity, occupancy, contact, closed, updated_at) VALUES (")
              .append(sid++).append(", ").append(q(s[0])).append(", ").append(q(s[1])).append(", ").append(s[2])
              .append(", 0, ").append(q(s[3])).append(", FALSE, ").append(now).append(");\n");
        }

        // ---- volunteers ----
        sb.append("\n-- Volunteers from DRS-Initial (phone numbers AES-GCM encrypted)\n");
        int vid = 1;
        for (String[] f : read("volunteers.csv")) {
            sb.append("INSERT INTO volunteers (volunteer_id, name, phone_enc, skill, available, registered_at) VALUES (")
              .append(vid++).append(", ").append(q(f[0])).append(", ").append(q(crypto.encrypt(f[1]))).append(", ")
              .append(q(f[2])).append(", TRUE, ").append(now).append(");\n");
        }

        // ---- reports + tasks ----
        sb.append("\n-- Disaster reports from DRS-Initial (signed by the importing admin) and the response tasks\n")
          .append("-- created when they were assessed (CoordinationService rules)\n");
        int repId = 1;
        int taskId = 1;
        StringBuilder tasks = new StringBuilder();
        for (String[] f : read("disaster_reports.csv")) {
            DisasterReport r = new DisasterReport(DisasterType.valueOf(f[0]), f[1], f[2], f[3], f[4]);
            r.setReportId(repId++);
            r.setReportedBy("admin");
            String signature = SignatureService.sign(r.canonicalContent(), keys.get("admin"));
            String status = "REPORTED";
            if (f.length > 5 && !f[5].isBlank()) {
                r.setSeverity(SeverityLevel.valueOf(f[5]));
                r.setPriorityScore(PriorityCalculator.calculate(r.getType(), r.getSeverity()));
                List<ResponseTask> created = CoordinationService.coordinateResponse(r, departments);
                status = r.getStatus().name();
                for (ResponseTask t : created) {
                    tasks.append("INSERT INTO response_tasks (task_id, report_id, department_id, volunteer_id, description, priority, status, created_at, updated_at) VALUES (")
                         .append(taskId++).append(", ").append(r.getReportId()).append(", ")
                         .append(t.getDepartment().getDepartmentId()).append(", NULL, ").append(q(t.getDescription()))
                         .append(", ").append(t.getPriority()).append(", 'ASSIGNED', ").append(now).append(", ").append(now)
                         .append(");\n");
                }
            }
            sb.append("INSERT INTO disaster_reports (report_id, type, location, description, reporter_name, reporter_phone_enc, severity, priority_score, status, reported_by, signature, date_reported, updated_at) VALUES (")
              .append(r.getReportId()).append(", ").append(q(f[0])).append(", ").append(q(f[1])).append(", ")
              .append(q(f[2])).append(", ").append(q(f[3])).append(", ").append(q(crypto.encrypt(f[4]))).append(", ")
              .append(r.getSeverity() == null ? "NULL" : q(r.getSeverity().name())).append(", ")
              .append(r.getPriorityScore()).append(", ").append(q(status)).append(", 'admin', ").append(q(signature))
              .append(", ").append(now).append(", ").append(now).append(");\n");
        }
        sb.append("\n").append(tasks);
        sb.append("\n-- The audit_log table starts empty; the server appends signed, hash-chained entries.\n")
          .append("-- Quick check:\nSELECT 'users' AS tbl, COUNT(*) AS n_rows FROM users UNION ALL SELECT 'departments', COUNT(*) FROM departments\n")
          .append("UNION ALL SELECT 'resources', COUNT(*) FROM resources UNION ALL SELECT 'volunteers', COUNT(*) FROM volunteers\n")
          .append("UNION ALL SELECT 'disaster_reports', COUNT(*) FROM disaster_reports UNION ALL SELECT 'response_tasks', COUNT(*) FROM response_tasks\n")
          .append("UNION ALL SELECT 'shelters', COUNT(*) FROM shelters;\n");
        return sb.toString();
    }

    /** Puts each top-level column/constraint of a CREATE TABLE on its own line. */
    static String pretty(String ddl) {
        StringBuilder out = new StringBuilder();
        int depth = 0;
        for (int i = 0; i < ddl.length(); i++) {
            char ch = ddl.charAt(i);
            if (ch == '(') {
                depth++;
                out.append(ch);
                if (depth == 1) {
                    out.append("\n  ");
                    while (i + 1 < ddl.length() && ddl.charAt(i + 1) == ' ') {
                        i++;
                    }
                }
            } else if (ch == ')') {
                if (depth == 1) {
                    out.append('\n');
                }
                depth--;
                out.append(ch);
            } else if (ch == ',' && depth == 1) {
                out.append(",\n  ");
                while (i + 1 < ddl.length() && ddl.charAt(i + 1) == ' ') {
                    i++;
                }
            } else {
                out.append(ch);
            }
        }
        return out.toString();
    }

    private static List<String[]> read(String file) throws IOException {
        try (InputStream in = SqlScriptGenerator.class.getResourceAsStream("/com/cqu/drs/data/drs-initial/" + file)) {
            if (in == null) {
                throw new IOException("Missing " + file);
            }
            BufferedReader r = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            List<String[]> rows = new ArrayList<>();
            String line = r.readLine(); // header
            while ((line = r.readLine()) != null) {
                if (!line.isBlank()) {
                    rows.add(com.cqu.drs.client.LegacyDataReader.splitCsv(line));
                }
            }
            return rows;
        }
    }
}
